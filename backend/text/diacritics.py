"""تشكيل الكلمات الملتبسة (diacritization) — تحسين اختياري للنطق.

⚠️ مهم: الموديل (VoiceTut-TTS) مدرّب على نص **غير مشكّل**، فالتشكيل ممكن
يفيد في كلمات معيّنة وممكن يضر في غيرها. عشان كده:

- مفعّل **اختياري** (افتراضي: مقفول).
- بيلمس **قائمة محصورة** من كلمات الإعلانات الشائعة بس.
- القاموس قابل للتعديل بحرّية من `DIACRITICS`.

الاستخدام:
    normalize_egyptian("عرض خاص", diacritics=True)
    # → "عَرْض خاص"
"""
from __future__ import annotations

import re

# كلمة (بالكتابة العادية) → الشكل المشكّل
DIACRITICS: dict[str, str] = {
    # منتجات وبيع
    "قهوة": "قَهْوَة",
    "عرض": "عَرْض",
    "سعر": "سِعْر",
    "خصم": "خَصْم",
    "منتج": "مُنْتَج",
    "جودة": "جَوْدَة",
    "توصيل": "تَوْصيل",
    "طلبات": "طَلَبات",
    "شركة": "شِرْكة",
    "خدمة": "خِدْمة",
    "عميل": "عَميل",
    "عملاء": "عُمَلاء",
    "فرع": "فَرْع",
    "مكان": "مَكان",
    "تجربة": "تَجْرِبة",
    "مجاناً": "مَجّاناً",
    "مجانا": "مَجّاناً",
    # وقت
    "بكرة": "بُكْرَة",
    "دلوقتي": "دِلْوَقْتي",
    "دقيقة": "دَقيقة",
    # كلمات عامية شائعة
    "أوي": "أَوي",
    "خالص": "خالِص",
    "كمان": "كَمان",
    "لازم": "لازِم",
    "ممكن": "مُمْكِن",
    "جامد": "جامِد",
    "تجنن": "تِجَنِّن",
    "أصلي": "أَصْلي",
    "طبيعي": "طَبيعي",
}

_WORDCHARS = r"0-9A-Za-z_\u0600-\u06FF"
# علامات التشكيل عشان نتجاهلها لو الكلمة مشكّلة أصلاً
_MARKS = "\u064b-\u0652\u0670\u0640"


def apply_diacritics(text: str) -> str:
    """يشكّل الكلمات الملتبسة من القائمة (كلمات مستقلة بس)."""
    out = text
    for word in sorted(DIACRITICS, key=len, reverse=True):
        # بنسمح بعلامات تشكيل موجودة بعد أي حرف قبل/بعد الكلمة
        pattern = rf"(?<![{_WORDCHARS}{_MARKS}]){re.escape(word)}(?![{_WORDCHARS}])"
        out = re.sub(pattern, DIACRITICS[word], out)
    return out
